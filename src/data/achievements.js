const slug = (s) =>
  s
    .toLowerCase()
    .replace(/['’“”"]/g, '')
    // Keep punctuation-only differences apart (“Mhm!” vs “Mhm...?”).
    .replace(/!/g, ' x ')
    .replace(/\?/g, ' q ')
    .replace(/\.\.\./g, ' dots ')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

// Stable ids: category + name (+ tier when a category repeats a name), so a
// player's saved progress survives reordering this file.
export const ACHIEVEMENTS = Object.entries(RAW).flatMap(([category, rows]) => {
  const seen = new Map();
  // A 4th field keeps the id of an entry that was renamed, so saved ticks stay.
  return rows.map(([rawTier, name, text, idName], order) => {
    const tier = rawTier[0];
    const hidden = rawTier.endsWith('h');
    let id = `${category}-${slug(idName ?? name) || 'unnamed'}`;
    const n = (seen.get(id) ?? 0) + 1;
    seen.set(id, n);
    if (n > 1) id = `${id}-${tier.toLowerCase()}${n > 2 ? n : ''}`;
    return { id, category, tier, hidden, name, text, order };
  });
});

// Characters named in Social achievements, for the character filter there.
export const ACHIEVEMENT_CHARACTERS = [
  ...new Set(
    ACHIEVEMENTS.filter((a) => a.category === 'social')
      .map((a) => a.text.match(/(?:Give|with) ([A-Z][a-z]+)/)?.[1])
      .filter((n) => n && n !== 'Affection'),
  ),
].sort();
